import assert from "node:assert/strict";
import { resolveRainHistoryWindow, RAIN_STARTUP_MINUTES } from "../src/rain-history-recovery-v1.js";
const start=Date.parse("2026-10-09T00:00:00Z");
const stamps=minutes=>minutes.map(m=>new Date(start+m*60000).toISOString());
const short=stamps([0,5,10,15,20,25,30,35]);
const native=resolveRainHistoryWindow(short,"30");
assert.equal(native.partial,false);
assert.equal(native.requestedMinutes,RAIN_STARTUP_MINUTES);
assert.equal(native.plan.length,6);
assert.equal(native.plan.at(-1).observedUtc,short.at(-1));
const tiny=resolveRainHistoryWindow(stamps([0,5,10]),"30");
assert.equal(tiny.partial,true);
assert.equal(tiny.plan.length,3);
const full=stamps(Array.from({length:13},(_,i)=>i*5));
const extended=resolveRainHistoryWindow(full,"60");
assert.equal(extended.partial,false);
assert.ok(extended.plan.length>=11);
assert.equal(resolveRainHistoryWindow(full,"120").partial,true);
assert.equal(resolveRainHistoryWindow(full,"120").plan.length,7);
assert.throws(()=>resolveRainHistoryWindow(short,"doppler-available"),RangeError);
console.log("PASS 30-minute BoM rain startup, source-backed 60/120/180 archive and source-short recovery.");
