import assert from "node:assert/strict";
import {createPlaybackPerformanceMeter} from "../src/playback-performance-meter-v1.js";
const meter=createPlaybackPerformanceMeter({windowSize:2});
let result=meter.record({frameMs:450,targetMs:450,windMs:40,radarMs:150,volumeMs:40});
assert.equal(result.overruns,0);
result=meter.record({frameMs:650,targetMs:225,windMs:80,radarMs:280,volumeMs:90});
assert.equal(result.overruns,1);
assert.equal(result.averageMs,550);
assert.ok(Math.abs(result.actualFps-1000/550)<.001);
result=meter.record({frameMs:100,targetMs:150});
assert.equal(result.samples,2);
assert.equal(result.overruns,1);
assert.throws(()=>meter.record({frameMs:-1,targetMs:150}),TypeError);
meter.clear();assert.equal(meter.summary().samples,0);
console.log("PASS measured frame cadence, rendered FPS, overrun diagnostics and bounded samples.");
