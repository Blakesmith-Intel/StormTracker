import assert from "node:assert/strict";
import { resolveRainHistoryWindow, RAIN_STARTUP_MINUTES } from "../src/rain-history-recovery-v1.js";
const start=Date.parse("2026-10-09T00:00:00Z");
const stamps=minutes=>minutes.map(m=>new Date(start+m*60000).toISOString());
const short=stamps([0,5,10,15,20,25,30,35]);
const partial=resolveRainHistoryWindow(short,"60");
assert.equal(partial.partial,true);
assert.equal(partial.starterMinutes,30);
assert.equal(partial.actualSpanMinutes,35);
assert.equal(partial.plan.at(0).observedUtc,short[1]);
assert.equal(partial.plan.at(-1).observedUtc,short.at(-1));
assert.equal((Date.parse(partial.plan.at(-1).observedUtc)-Date.parse(partial.plan[0].observedUtc))/60000,RAIN_STARTUP_MINUTES);
const full=stamps(Array.from({length:13},(_,i)=>i*5));
const complete=resolveRainHistoryWindow(full,"60");
assert.equal(complete.partial,false);
assert.equal(complete.starterMinutes,null);
assert.ok(complete.plan.length>=11);
assert.equal(resolveRainHistoryWindow(full,"120").partial,true);
assert.equal(resolveRainHistoryWindow(full,"120").plan.length,7);
const tiny=resolveRainHistoryWindow(stamps([0,5,10]),"60");
assert.equal(tiny.plan.length,3); // never invent a missing 30 minutes
assert.throws(()=>resolveRainHistoryWindow(short,"doppler-available"),RangeError);
console.log("PASS native 30-min rain startup, partial archive recovery and 60/120/180 progression.");
