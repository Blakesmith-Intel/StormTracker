function gaugeCoordinates(feature) {
  const point=feature?.geometry?.type==="Point" ? feature.geometry.coordinates : null;
  const p=feature?.properties??{};
  const lon=Number(point?.[0] ?? p.long ?? p.longitude);
  const lat=Number(point?.[1] ?? p.lat ?? p.latitude);
  if(!Number.isFinite(lon)||!Number.isFinite(lat)||
    lon<135||lon>156||lat< -31||lat> -8)return null;
  return [lon,lat];
}

// Local equirectangular point-to-segment distance is adequate only for the
// conservative 125 km screening decision; geographic distance is approximate.
export function approximateQueenslandCoastDistanceKm(feature){
  const point=gaugeCoordinates(feature);
  if(!point)return null;
  const [lon,lat]=point;
  const lonToKm=111.195*Math.cos(lat*Math.PI/180);
  const latToKm=111.195;
  let best=Infinity;
  for(const [a,b,c,d] of QLD_APPROX_COAST_SEGMENTS){
    const x=(a-lon)*lonToKm,y=(b-lat)*latToKm;
    const vx=(c-a)*lonToKm,vy=(d-b)*latToKm;
    const u=Math.min(1,Math.max(0,-(x*vx+y*vy)/(vx*vx+vy*vy||1)));
    best=Math.min(best,Math.hypot(x+u*vx,y+u*vy));
  }
  return Number.isFinite(best)?best:null;
}

export function gaugeRiseScreeningZone(feature){
  const coastKm=approximateQueenslandCoastDistanceKm(feature);
  return {
    coastDistanceKm:coastKm,
    zone:coastKm===null?"unknown":
      coastKm<INLAND_COAST_BUFFER_KM?"coastal-uncertain":"inland"
  };
}
